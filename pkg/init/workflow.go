package initialize

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/antigravity/monoflow/pkg/graph"
)

// MonoflowSourceRepo is where CI builds MonoFlow from when no binary is committed.
const MonoflowSourceRepo = "https://github.com/M0xoo/monoflow"

// GitHubWorkflow renders an economical GitHub Actions workflow: it runs once per PR head
// (not on every branch push), cancels superseded runs, skips drafts and docs-only changes,
// and verifies only the packages affected relative to the PR base, reusing the MonoFlow
// cache. Local MonoFlow gates already keep red commits from being pushed.
func GitHubWorkflow(g *graph.DependencyGraph) string {
	langs := map[graph.Language]bool{}
	for _, p := range g.GetAllPackages() {
		langs[p.Language] = true
	}
	var setup []string
	goVersionFile := "go.mod"
	if _, err := os.Stat(filepath.Join(g.RootDir, "go.work")); err == nil {
		goVersionFile = "go.work"
	}
	if langs[graph.LangGo] {
		setup = append(setup, fmt.Sprintf(`      - uses: actions/setup-go@v5
        with:
          go-version-file: %s
          cache: false`, goVersionFile))
	}
	if !langs[graph.LangGo] {
		// Fallback: MonoFlow is built from source when no release binary is available.
		setup = append(setup, `      - uses: actions/setup-go@v5
        if: hashFiles('.agents/bin/monoflow-linux-amd64') == ''
        with:
          go-version: stable
          cache: false`)
	}
	if langs[graph.LangTypeScript] || langs[graph.LangJavaScript] {
		setup = append(setup, `      - uses: actions/setup-node@v4
        with:
          node-version: "20"`)
	}
	if langs[graph.LangPython] {
		setup = append(setup, `      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"`)
		// The checks run through the project manager (uv run, poetry run): CI needs it too.
		var uv, poetry, pdm bool
		for _, p := range g.GetAllPackages() {
			cmds := p.TestCmd + " " + p.LintCmd + " " + p.TypecheckCmd
			uv = uv || strings.Contains(cmds, "uv run ") || strings.Contains(cmds, "uvx ")
			poetry = poetry || strings.Contains(cmds, "poetry run ")
			pdm = pdm || strings.Contains(cmds, "pdm run ")
		}
		if uv {
			setup = append(setup, `      - uses: astral-sh/setup-uv@v6`)
		}
		if poetry {
			setup = append(setup, `      - run: pipx install poetry`)
		}
		if pdm {
			setup = append(setup, `      - run: pipx install pdm`)
		}
	}
	if langs[graph.LangRust] {
		setup = append(setup, `      - uses: dtolnay/rust-toolchain@stable`)
	}

	return `# Generated by monoflow init --setup-gh-actions. Regenerate rather than edit.
name: monoflow-ci
on:
  pull_request:
    types: [opened, synchronize, reopened, ready_for_review]
    paths-ignore: ["**/*.md", "**/*.mdx", "**/*.rst", "docs/**", "**/docs/**", "LICENSE*", ".agents/**", ".claude/**", ".opencode/**"]
  push:
    branches: [main, master]
    paths-ignore: ["**/*.md", "**/*.mdx", "**/*.rst", "docs/**", "**/docs/**", "LICENSE*", ".agents/**", ".claude/**", ".opencode/**"]

# One run per PR head: a newer push cancels the superseded run.
concurrency:
  group: monoflow-ci-${{ github.event.pull_request.number || github.ref }}
  cancel-in-progress: true

jobs:
  affected:
    if: github.event_name != 'pull_request' || github.event.pull_request.draft == false
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
` + strings.Join(setup, "\n") + `
      - name: Restore MonoFlow cache
        uses: actions/cache@v4
        with:
          path: .agents/cache
          key: monoflow-${{ runner.os }}-${{ github.sha }}
          restore-keys: monoflow-${{ runner.os }}-
      - name: Install MonoFlow
        run: |
          if [ -x .agents/bin/monoflow-linux-amd64 ]; then
            install -m 0755 .agents/bin/monoflow-linux-amd64 /usr/local/bin/monoflow
          elif curl -fsSL -o /tmp/monoflow ` + MonoflowSourceRepo + `/releases/latest/download/monoflow-linux-amd64; then
            install -m 0755 /tmp/monoflow /usr/local/bin/monoflow
          else
            command -v go >/dev/null || { echo "MonoFlow needs Go to build from source"; exit 1; }
            git clone -q --depth 1 ` + MonoflowSourceRepo + ` /tmp/monoflow-src
            (cd /tmp/monoflow-src && go build -o /usr/local/bin/monoflow ./cmd/monoflow)
          fi
      - name: Reuse agent-verified results (PRs only; main always verifies for real)
        if: github.event_name == 'pull_request'
        run: monoflow ci proofs import --commit=${{ github.event.pull_request.head.sha }} || true
      - name: Verify affected packages
        env:
          BASE: ${{ github.event_name == 'pull_request' && format('origin/{0}', github.base_ref) || github.event.before }}
        run: monoflow verify --affected --base="$BASE"
`
}

// WriteGitHubWorkflow writes .github/workflows/monoflow-ci.yml.
func WriteGitHubWorkflow(repoRoot string) (string, error) {
	g, err := graph.LoadOrDiscover(repoRoot)
	if err != nil {
		return "", err
	}
	path := filepath.Join(repoRoot, ".github", "workflows", "monoflow-ci.yml")
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return "", err
	}
	return path, os.WriteFile(path, []byte(GitHubWorkflow(g)), 0644)
}
