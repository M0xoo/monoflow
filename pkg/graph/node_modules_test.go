package graph

import (
	"os"
	"path/filepath"
	"strconv"
	"testing"
	"time"
)

// A marker without a live installer (a copy that got committed, or a crashed install) must not
// make checks wait: the outer loop once waited 10 minutes on a committed one.
func TestWaitForDepsIgnoresStaleMarker(t *testing.T) {
	dir := t.TempDir()
	marker := filepath.Join(dir, DepsMarker)
	_ = os.MkdirAll(filepath.Dir(marker), 0755)
	for _, content := range []string{"", "999999"} {
		_ = os.WriteFile(marker, []byte(content), 0644)
		start := time.Now()
		WaitForDeps(dir, 5*time.Second)
		if time.Since(start) > time.Second {
			t.Fatalf("marker %q: waited %v", content, time.Since(start))
		}
	}
	// A live installer is waited for.
	_ = os.WriteFile(marker, []byte(strconv.Itoa(os.Getpid())), 0644)
	start := time.Now()
	WaitForDeps(dir, 1200*time.Millisecond)
	if time.Since(start) < time.Second {
		t.Fatal("should wait while the installer runs")
	}
}
