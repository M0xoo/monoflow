package graph

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// OverlayNodeModules gives a checkout of the repo (worktree, outer-loop or baseline checkout) node_modules directories (root and per package)
// whose external entries link to the root's installed dependencies — no reinstall — while
// workspace-package entries link to the worktree's own package directories. Linking the
// root node_modules wholesale made require("@scope/pkg") load the root checkout's code, so
// agents verified the unedited package.
func OverlayNodeModules(root, wtPath string) {
	if _, err := os.Stat(filepath.Join(root, "node_modules")); err != nil {
		return // dependencies not installed at the root
	}
	g, err := LoadOrDiscover(wtPath)
	if err != nil {
		return
	}
	workspace := map[string]string{}
	dirs := []string{"."}
	for _, p := range g.GetAllPackages() {
		if p.Language == LangJavaScript || p.Language == LangTypeScript {
			workspace[p.Name] = p.Path
			dirs = append(dirs, p.Path)
		}
	}
	link := func(dst, name, rootEntry string) {
		target := rootEntry
		if path, ok := workspace[name]; ok {
			if _, err := os.Stat(filepath.Join(wtPath, path)); err == nil {
				target = filepath.Join(wtPath, path)
			}
		}
		_ = os.MkdirAll(filepath.Dir(dst), 0755)
		_ = os.Remove(dst)
		_ = os.Symlink(target, dst)
	}
	for _, d := range dirs {
		src := filepath.Join(root, d, "node_modules")
		dst := filepath.Join(wtPath, d, "node_modules")
		entries, err := os.ReadDir(src)
		if err != nil {
			continue
		}
		if _, err := os.Stat(filepath.Join(wtPath, d)); err != nil {
			continue // package not projected into this worktree
		}
		if fi, err := os.Lstat(dst); err == nil && fi.Mode()&os.ModeSymlink != 0 {
			_ = os.Remove(dst)
		}
		_ = os.MkdirAll(dst, 0755)
		for _, e := range entries {
			if strings.HasPrefix(e.Name(), "@") && e.IsDir() {
				scoped, _ := os.ReadDir(filepath.Join(src, e.Name()))
				for _, s := range scoped {
					name := e.Name() + "/" + s.Name()
					link(filepath.Join(dst, e.Name(), s.Name()), name, filepath.Join(src, name))
				}
				continue
			}
			link(filepath.Join(dst, e.Name()), e.Name(), filepath.Join(src, e.Name()))
		}
	}
}

// pnpm workspaces get a real install instead of the overlay: Vite (vitest) refuses files whose
// real path is outside the project root, and the overlay's links resolve into the main
// checkout, so in a worktree 48 of 50 trpc react-query test files failed to load, and the same
// failure on the baseline hid it as "preexisting". With the lockfile unchanged, an offline
// install from pnpm's store takes ~25 s on trpc.

// DepsMarker exists while a worktree's dependencies are being installed in the background.
const DepsMarker = ".agents/deps-installing"

// UsesPnpmInstall reports whether a checkout of root should get its own pnpm install.
func UsesPnpmInstall(root string) bool {
	_, lock := os.Stat(filepath.Join(root, "pnpm-lock.yaml"))
	_, mods := os.Stat(filepath.Join(root, "node_modules"))
	return lock == nil && mods == nil
}

// PnpmInstallCmd installs dir's dependencies from the local store without network, never
// prompting.
func PnpmInstallCmd(dir string) *exec.Cmd {
	cmd := exec.Command("pnpm", "install", "--offline", "--frozen-lockfile", "--config.confirmModulesPurge=false")
	cmd.Dir = dir
	cmd.Env = append(os.Environ(), "CI=true")
	return cmd
}

// PrepareNodeModules gives a checkout of root its dependencies: a pnpm install for pnpm
// workspaces (falling back to the overlay if it fails), the overlay otherwise.
func PrepareNodeModules(root, dir string) {
	if UsesPnpmInstall(root) {
		if err := PnpmInstallCmd(dir).Run(); err == nil {
			return
		}
	}
	OverlayNodeModules(root, dir)
}

// WaitForDeps blocks (up to timeout) while a background install of dir's dependencies runs.
func WaitForDeps(dir string, timeout time.Duration) {
	deadline := time.Now().Add(timeout)
	for time.Now().Before(deadline) {
		fi, err := os.Stat(filepath.Join(dir, DepsMarker))
		if err != nil || time.Since(fi.ModTime()) > 15*time.Minute {
			return
		}
		time.Sleep(500 * time.Millisecond)
	}
}
