package worktree

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"
)

// In a worktree, require("@acme/ui") must load the worktree's edited package, not the root's.
func TestWorktreeNodeModulesResolveWorkspacePackagesToWorktree(t *testing.T) {
	root := t.TempDir()
	write := func(rel, s string) {
		p := filepath.Join(root, rel)
		_ = os.MkdirAll(filepath.Dir(p), 0755)
		_ = os.WriteFile(p, []byte(s), 0644)
	}
	write("package.json", `{"private":true,"workspaces":["packages/*"]}`)
	write("packages/ui/package.json", `{"name":"@acme/ui","main":"index.js"}`)
	write("packages/ui/index.js", "module.exports = 'root'\n")
	write("packages/web/package.json", `{"name":"@acme/web","dependencies":{"@acme/ui":"*"}}`)
	write(".gitignore", "node_modules\n")
	for _, args := range [][]string{{"init", "-q", "-b", "main"}, {"config", "user.email", "t@t"}, {"config", "user.name", "t"}, {"add", "-A"}, {"commit", "-qm", "init"}} {
		cmd := exec.Command("git", args...)
		cmd.Dir = root
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Fatalf("git %v: %v %s", args, err, out)
		}
	}
	// What npm/pnpm create at the root: relative workspace links + an external package.
	_ = os.MkdirAll(filepath.Join(root, "node_modules", "@acme"), 0755)
	_ = os.Symlink("../../packages/ui", filepath.Join(root, "node_modules", "@acme", "ui"))
	write("node_modules/left-pad/index.js", "module.exports = 'pad'\n")

	info, err := NewManager(root).Create("js-agent")
	if err != nil {
		t.Fatal(err)
	}
	_ = os.WriteFile(filepath.Join(info.Path, "packages/ui/index.js"), []byte("module.exports = 'worktree'\n"), 0644)

	got, err := os.ReadFile(filepath.Join(info.Path, "node_modules", "@acme", "ui", "index.js"))
	if err != nil || string(got) != "module.exports = 'worktree'\n" {
		t.Fatalf("@acme/ui must resolve to the worktree's package, got %q (%v)", got, err)
	}
	if pad, err := os.ReadFile(filepath.Join(info.Path, "node_modules", "left-pad", "index.js")); err != nil || string(pad) != "module.exports = 'pad'\n" {
		t.Fatalf("external deps must come from the root install, got %q (%v)", pad, err)
	}
	if out, _ := exec.Command("git", "-C", info.Path, "status", "--porcelain").Output(); strings.Contains(string(out), "node_modules") {
		t.Fatalf("overlay must not show up in git status: %s", out)
	}
}
